# Solution
num1 = -18.75
base = 2
exp = 8
float_val = 3.14159265

print(f"Original number       : {num1}")
print(f"Using abs()           : {abs(num1)}")
print(f"Using pow({base}, {exp})     : {pow(base, exp)}")
print(f"Using round({float_val}, 2): {round(float_val, 2)}")
print(f"Using round({float_val}, 4): {round(float_val, 4)}")
