# Solution
celsius = 37.0  # Human body temperature

fahrenheit = (celsius * 9 / 5) + 32

print("Temperature Conversion:")
print(f"Celsius    : {celsius}°C")
print(f"Fahrenheit : {fahrenheit:.2f}°F")
