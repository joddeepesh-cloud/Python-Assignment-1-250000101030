# Solution
# Cube
side = 4.0
volume_cube = side ** 3

# Cuboid
l = 6.0
b = 4.0
h = 5.0
volume_cuboid = l * b * h

print("Volume of Cube (side = 4.0):", volume_cube)
print("Volume of Cuboid (length = 6.0, breadth = 4.0, height = 5.0):", volume_cuboid)
