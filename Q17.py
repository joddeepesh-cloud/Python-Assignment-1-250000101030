# Solution
km = 5.5

metres = km * 1000
centimetres = km * 100000

print(f"Distance in Kilometres  : {km} km")
print(f"Distance in Metres      : {metres:.2f} m")
print(f"Distance in Centimetres : {centimetres:.2f} cm")
