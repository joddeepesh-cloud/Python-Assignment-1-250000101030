sub2 = 90.0
sub3 = 88.0
sub4 = 92.0
sub5 = 89.0

total_marks = sub1 + sub2 + sub3 + sub4 + sub5
average_marks = total_marks / 5

print("Subject Marks: 85.0, 90.0, 88.0, 92.0, 89.0")
