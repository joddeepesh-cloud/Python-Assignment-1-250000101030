# Solution
radius = 5.0
PI = 3.141592653589793

area = PI * radius * radius
circumference = 2 * PI * radius

print("Circle Dimensions:")
print("Radius        :", radius)
print("Area          :", round(area, 2))
print("Circumference :", round(circumference, 2))
